export function productionReason(value){
 return typeof value==='string'&&reasons.has(value)?value:'PRODUCTION_BLOCKED';
}
export function productionFailure(error){
 return productionReason(error?.message==='PYTHON_STAGE_FAILED'&&error.reasonCode
  ?error.reasonCode:error?.message);
}
export function stageFailureReason(stdout){
 try{
  const result=JSON.parse(stdout);
  return result?.status==='BLOCKED'?productionReason(result.reason_code):'PRODUCTION_BLOCKED';
 }catch{return 'PRODUCTION_BLOCKED';}
}

